-- Token hashes never change once stored.
create or replace function public.pro_work_client_invitation_guard() returns trigger
language plpgsql security invoker set search_path=public,pg_temp as $$
begin
 if new.token_hash is distinct from old.token_hash or new.owner_id is distinct from old.owner_id or new.work_id is distinct from old.work_id or new.expires_at is distinct from old.expires_at or new.created_at is distinct from old.created_at
  or old.accepted_at is not null and (new.accepted_at is distinct from old.accepted_at or new.accepted_by is distinct from old.accepted_by)
  or old.revoked_at is not null and new.revoked_at is distinct from old.revoked_at then raise exception 'Invitation identity is immutable' using errcode='23514';end if;
 return new;
end $$;
