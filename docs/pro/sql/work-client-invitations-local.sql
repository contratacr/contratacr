-- LOCAL PRO ONLY. Round 1 after the manual walkthrough (2026-11-12): link a customer ACCOUNT to an
-- existing job ("Invitar al cliente al proyecto"), and let a customer who accepted an estimate shared
-- by code join the job that results from it.
--
-- Model: every customer reader of the suite (customer view, contracts, files, file versions, idea
-- boards, updates, daily logs, selections, allowances, schedule, punch list) already authorizes the
-- customer through ONE confirmed pro_appointment_requests row of the job. A link therefore inserts
-- that same row with origin='project_invite' (not an appointment: no time, no reminders, no notice,
-- excluded from lead lists and from the provider request list; the agenda sync ignores it).
--
-- Invitation: random 32-byte token generated by the server route, shown once to the owner, only its
-- SHA-256 is stored (domain-prefixed by the route). Expires (1..30 days, default 7), revocable, single
-- use; creating a new one revokes the previous open invitation of the job. Nothing is e-mailed.
-- Estimate consent: the verified recipient of an ACCEPTED publication may opt in; the link is made
-- when (or if already) the owner continues that accepted estimate into a job.
begin;
create table if not exists public.pro_work_client_invitations(
 id uuid primary key,
 owner_id uuid not null references public.profiles(id) on delete cascade,
 work_id text not null,
 token_hash text not null unique check(token_hash~'^[a-f0-9]{64}$'),
 created_at timestamptz not null default clock_timestamp(),
 expires_at timestamptz not null,
 revoked_at timestamptz,
 accepted_by uuid references public.profiles(id) on delete cascade,
 accepted_at timestamptz,
 request_id uuid,
 check(expires_at>created_at),
 check((accepted_by is null)=(accepted_at is null)),
 check(accepted_at is null or revoked_at is null),
 foreign key(owner_id,work_id) references public.pro_work(user_id,id) on delete cascade
);
create index if not exists pro_work_client_invitations_work on public.pro_work_client_invitations(owner_id,work_id,created_at desc);
create table if not exists public.pro_work_client_invitation_actions(
 actor_id uuid not null references public.profiles(id) on delete cascade,action_id uuid not null,
 input jsonb not null,result jsonb not null,at timestamptz not null default clock_timestamp(),
 primary key(actor_id,action_id),check(not(input?'token'))
);
create table if not exists public.pro_work_client_link_consents(
 publication_id uuid primary key references public.pro_private_estimate_publications(id) on delete cascade,
 owner_id uuid not null references public.profiles(id) on delete cascade,
 client_user_id uuid not null references public.profiles(id) on delete cascade,
 at timestamptz not null default clock_timestamp(),
 request_id uuid
);

create or replace function public.pro_work_client_invitation_state(p_row public.pro_work_client_invitations) returns text
language sql stable security invoker set search_path=public,pg_temp as $$
 select case when p_row.accepted_at is not null then 'accepted' when p_row.revoked_at is not null then 'revoked'
  when p_row.expires_at<=clock_timestamp() then 'expired' else 'active' end $$;
create or replace function public.pro_work_client_invitation_json(p_row public.pro_work_client_invitations) returns jsonb
language sql stable security invoker set search_path=public,pg_temp as $$
 select jsonb_build_object('id',p_row.id,'state',public.pro_work_client_invitation_state(p_row),'createdAt',p_row.created_at,
  'expiresAt',p_row.expires_at,'revokedAt',p_row.revoked_at,'acceptedAt',p_row.accepted_at) $$;
-- Linked customer account of the job (any origin), the same rule as every shared reader.
create or replace function public.pro_work_client_link_json(p_owner uuid,p_work text) returns jsonb
language sql stable security invoker set search_path=public,pg_temp as $$
 select jsonb_build_object('requestId',r.id,'name',r.client_name,'origin',r.origin,'linkedAt',r.updated_at)
 from public.pro_appointment_requests r join public.profiles c on c.id=r.client_user_id
 where r.owner_id=p_owner and r.work_id=p_work and r.status in('confirmed','completed') and not coalesce(c.is_disabled,false)
 order by r.updated_at desc,r.id desc limit 1 $$;

-- Internal: link p_client to the owner's job. Caller holds the owner mutex
-- (hashtextextended(owner,0), the same lock as the appointment workflow).
create or replace function public.pro_work_client_link_apply(p_owner uuid,p_work text,p_client uuid) returns uuid
language plpgsql security invoker set search_path=public,pg_temp as $$
declare w public.pro_work;prof public.professionals;r public.pro_appointment_requests;who public.profiles;rid uuid;prior text;label text;
begin
 if p_client is null or p_owner is null or p_client=p_owner then raise exception 'Own job' using errcode='42501',hint='pro_invite_own';end if;
 select * into who from public.profiles where id=p_client and not coalesce(is_disabled,false);
 if not found then raise exception 'Account unavailable' using errcode='42501';end if;
 select * into w from public.pro_work where user_id=p_owner and id=p_work;
 if not found or coalesce(w.cancelled,false) then raise exception 'Job unavailable' using errcode='40001',hint='pro_invite_work';end if;
 select * into prof from public.professionals where profile_id=p_owner and not coalesce(is_banned,false) order by id limit 1;
 if not found then raise exception 'Professional profile required' using errcode='22023',hint='pro_invite_profile';end if;
 label:=coalesce(nullif(left(btrim(w.service),160),''),'Proyecto');
 select * into r from public.pro_appointment_requests where owner_id=p_owner and work_id=p_work for update;
 prior:=current_setting('contratacr.project_link',true);
 if found then
  if r.client_user_id=p_client and r.status in('confirmed','completed') then return r.id;end if;
  if r.origin<>'project_invite' or r.status in('confirmed','completed') then raise exception 'Another customer is linked' using errcode='40001',hint='pro_invite_linked';end if;
  -- A previously unlinked invitation row is reused (one row per job): new account, confirmed again.
  perform set_config('contratacr.project_link',r.id::text,true);
  update public.pro_appointment_requests set client_user_id=p_client,client_name=left(coalesce(nullif(btrim(who.full_name),''),nullif(btrim(w.client),''),'Cliente'),160),
   service=label,status='confirmed',revision=revision+1,updated_at=now() where id=r.id;
  perform set_config('contratacr.project_link',coalesce(prior,''),true);rid:=r.id;
 else
  rid:=gen_random_uuid();
  insert into public.pro_appointment_requests(id,professional_id,owner_id,client_user_id,client_name,professional_name,professional_slug,service,duration_minutes,location_kind,location_text,note,status,revision,work_id,origin)
  values(rid,prof.id,p_owner,p_client,left(coalesce(nullif(btrim(who.full_name),''),nullif(btrim(w.client),''),'Cliente'),160),left(coalesce(nullif(btrim(prof.business_name),''),'Profesional'),160),prof.slug,
   label,60,'agree','','','confirmed',0,p_work,'project_invite');
 end if;
 -- 'project_link' is not an appointment notice action: no notification, no reminder.
 insert into public.pro_appointment_events(request_id,actor_id,side,action,note,status) values(rid,p_client,'client','project_link','','confirmed');
 return rid;
end $$;

-- Rows created by invitation change only through this module (flag set by the functions above).
create or replace function public.pro_work_client_link_guard() returns trigger
language plpgsql security invoker set search_path=public,pg_temp as $$
begin
 if new.origin is distinct from old.origin then raise exception 'Request origin is immutable' using errcode='23514';end if;
 if old.origin='project_invite' and coalesce(current_setting('contratacr.project_link',true),'')<>old.id::text then raise exception 'Use the project invitation workflow' using errcode='23514',hint='pro_invite_workflow';end if;
 return new;
end $$;
drop trigger if exists pro_work_client_link_guard on public.pro_appointment_requests;
create trigger pro_work_client_link_guard before update on public.pro_appointment_requests for each row execute function public.pro_work_client_link_guard();

create or replace function public.pro_work_client_invitations_read(p_actor uuid,p_work text) returns jsonb
language plpgsql stable security invoker set search_path=public,pg_temp as $$
declare w public.pro_work;items jsonb;linked jsonb;has_profile boolean;
begin
 if not coalesce(public.pro_private_work_tools_enabled(p_actor),false) then raise exception 'Forbidden' using errcode='42501';end if;
 if p_work is null or length(p_work) not between 1 and 160 then raise exception 'Invalid invitation query' using errcode='22023';end if;
 select * into w from public.pro_work where user_id=p_actor and id=p_work;if not found then return null;end if;
 linked:=public.pro_work_client_link_json(p_actor,p_work);
 select exists(select 1 from public.professionals where profile_id=p_actor and not coalesce(is_banned,false)) into has_profile;
 select coalesce(jsonb_agg(public.pro_work_client_invitation_json(i) order by i.created_at desc),'[]'::jsonb) into items
  from (select * from public.pro_work_client_invitations where owner_id=p_actor and work_id=p_work order by created_at desc limit 10) i;
 return jsonb_build_object('workId',p_work,'service',w.service,'client',w.client,'cancelled',coalesce(w.cancelled,false),'linked',linked,'invitations',items,
  'canInvite',linked is null and not coalesce(w.cancelled,false) and has_profile,'profileMissing',not has_profile);
end $$;

-- Customer record ("ficha del cliente"): that customer's jobs with their linked account, newest first.
create or replace function public.pro_work_client_invite_jobs(p_actor uuid,p_client text) returns jsonb
language plpgsql stable security invoker set search_path=public,pg_temp as $$
declare items jsonb;
begin
 if not coalesce(public.pro_private_work_tools_enabled(p_actor),false) then raise exception 'Forbidden' using errcode='42501';end if;
 if p_client is null or length(p_client) not between 1 and 160 then raise exception 'Invalid customer query' using errcode='22023';end if;
 if not exists(select 1 from public.pro_clients where user_id=p_actor and id=p_client) then return null;end if;
 select coalesce(jsonb_agg(x.content order by x.position desc),'[]'::jsonb) into items from(
  select w.position,jsonb_build_object('workId',w.id,'service',w.service,'stage',w.stage,'cancelled',coalesce(w.cancelled,false),'linked',public.pro_work_client_link_json(p_actor,w.id)) content
  from public.pro_work w where w.user_id=p_actor and w."clientId"=p_client order by w.position desc limit 20) x;
 return jsonb_build_object('clientId',p_client,'items',items);
end $$;
create or replace function public.pro_work_client_invitations_mutate(p_actor uuid,p_input jsonb) returns jsonb
language plpgsql security invoker set search_path=public,pg_temp as $$
declare act text;aid uuid;wid text;iid uuid;keys text[];prior public.pro_work_client_invitation_actions;w public.pro_work;i public.pro_work_client_invitations;r public.pro_appointment_requests;days integer;result jsonb;flag text;
begin
 if not coalesce(public.pro_private_work_tools_enabled(p_actor),false) then raise exception 'Forbidden' using errcode='42501';end if;
 if jsonb_typeof(p_input) is distinct from 'object' or jsonb_typeof(p_input->'action') is distinct from 'string' then raise exception 'Invalid invitation' using errcode='22023';end if;
 act:=p_input->>'action';select array_agg(key order by key) into keys from jsonb_object_keys(p_input) key;
 if keys is distinct from (case act when 'create' then array['action','actionId','expiresInDays','invitationId','tokenHash','workId'] when 'revoke' then array['action','actionId','invitationId','workId'] when 'unlink' then array['action','actionId','requestId','workId'] end)
  or jsonb_typeof(p_input->'workId') is distinct from 'string' or length(p_input->>'workId') not between 1 and 160 then raise exception 'Invalid invitation fields' using errcode='22023';end if;
 aid:=(p_input->>'actionId')::uuid;wid:=p_input->>'workId';
 if act='create' and (not coalesce(p_input->>'tokenHash'~'^[a-f0-9]{64}$',false) or jsonb_typeof(p_input->'expiresInDays') is distinct from 'number' or not coalesce(p_input->>'expiresInDays'~'^[0-9]{1,2}$',false)) then raise exception 'Invalid invitation values' using errcode='22023';end if;
 if act='create' then days:=(p_input->>'expiresInDays')::integer;if days not between 1 and 30 then raise exception 'Invalid expiry' using errcode='22023';end if;end if;
 if act in('create','revoke') then iid:=(p_input->>'invitationId')::uuid;end if;
 perform pg_advisory_xact_lock(hashtextextended(p_actor::text,0));
 if not coalesce(public.pro_private_work_tools_enabled(p_actor),false) then raise exception 'Forbidden' using errcode='42501';end if;
 select * into prior from public.pro_work_client_invitation_actions where actor_id=p_actor and action_id=aid;
 if found then if prior.input is distinct from p_input then raise exception 'Action identity reused' using errcode='22023';end if;return prior.result||jsonb_build_object('replayed',true);end if;
 select * into w from public.pro_work where user_id=p_actor and id=wid;if not found then raise exception 'Forbidden' using errcode='42501';end if;
 if act='create' then
  if coalesce(w.cancelled,false) then raise exception 'Job cancelled' using errcode='40001',hint='pro_invite_work';end if;
  if public.pro_work_client_link_json(p_actor,wid) is not null then raise exception 'Customer already linked' using errcode='40001',hint='pro_invite_linked';end if;
  if not exists(select 1 from public.professionals where profile_id=p_actor and not coalesce(is_banned,false)) then raise exception 'Professional profile required' using errcode='22023',hint='pro_invite_profile';end if;
  if exists(select 1 from public.pro_work_client_invitations where id=iid) or exists(select 1 from public.pro_work_client_invitations where token_hash=p_input->>'tokenHash') then raise exception 'Invitation identity reused' using errcode='40001';end if;
  if (select count(*) from public.pro_work_client_invitations where owner_id=p_actor and created_at>clock_timestamp()-interval '1 day')>=50 then raise exception 'Invitation limit' using errcode='54000';end if;
  update public.pro_work_client_invitations set revoked_at=clock_timestamp() where owner_id=p_actor and work_id=wid and accepted_at is null and revoked_at is null and expires_at>clock_timestamp();
  insert into public.pro_work_client_invitations(id,owner_id,work_id,token_hash,expires_at) values(iid,p_actor,wid,p_input->>'tokenHash',clock_timestamp()+make_interval(days=>days)) returning * into i;
  result:=jsonb_build_object('action','create','invitation',public.pro_work_client_invitation_json(i));
 elsif act='revoke' then
  select * into i from public.pro_work_client_invitations where id=iid and owner_id=p_actor and work_id=wid for update;
  if not found then raise exception 'Invitation unavailable' using errcode='42501';end if;
  if i.accepted_at is not null then raise exception 'Invitation already used' using errcode='40001',hint='pro_invite_used';end if;
  if i.revoked_at is null then update public.pro_work_client_invitations set revoked_at=clock_timestamp() where id=i.id returning * into i;end if;
  result:=jsonb_build_object('action','revoke','invitation',public.pro_work_client_invitation_json(i));
 else
  select * into r from public.pro_appointment_requests where id=(p_input->>'requestId')::uuid and owner_id=p_actor and work_id=wid for update;
  if not found then raise exception 'Link unavailable' using errcode='42501';end if;
  -- Accounts that booked through the public calendar keep the appointment workflow.
  if r.origin<>'project_invite' then raise exception 'Booking link' using errcode='40001',hint='pro_invite_booking';end if;
  if r.status not in('confirmed','completed') then raise exception 'Already unlinked' using errcode='40001';end if;
  flag:=current_setting('contratacr.project_link',true);perform set_config('contratacr.project_link',r.id::text,true);
  update public.pro_appointment_requests set status='cancelled',revision=revision+1,updated_at=now() where id=r.id;
  perform set_config('contratacr.project_link',coalesce(flag,''),true);
  insert into public.pro_appointment_events(request_id,actor_id,side,action,note,status) values(r.id,p_actor,'provider','project_unlink','','cancelled');
  result:=jsonb_build_object('action','unlink','requestId',r.id);
 end if;
 insert into public.pro_work_client_invitation_actions(actor_id,action_id,input,result) values(p_actor,aid,p_input,result);
 return result;
end $$;

-- Customer side. Reveals only the professional's public name, the job title and the expiry.
create or replace function public.pro_work_client_invitation_preview(p_actor uuid,p_token_hash text) returns jsonb
language plpgsql stable security invoker set search_path=public,pg_temp as $$
declare i public.pro_work_client_invitations;w public.pro_work;prof public.professionals;st text;linked jsonb;
begin
 if not exists(select 1 from public.profiles where id=p_actor and not coalesce(is_disabled,false)) then raise exception 'Forbidden' using errcode='42501';end if;
 if not coalesce(p_token_hash~'^[a-f0-9]{64}$',false) then raise exception 'Invalid code' using errcode='22023';end if;
 select * into i from public.pro_work_client_invitations where token_hash=p_token_hash;
 if not found then return jsonb_build_object('state','unknown');end if;
 if i.accepted_by=p_actor then return jsonb_build_object('state','linked','requestId',i.request_id);end if;
 st:=public.pro_work_client_invitation_state(i);
 if st='accepted' then return jsonb_build_object('state','used');end if;
 if st<>'active' then return jsonb_build_object('state',st);end if;
 if i.owner_id=p_actor then return jsonb_build_object('state','own');end if;
 select * into w from public.pro_work where user_id=i.owner_id and id=i.work_id;
 linked:=public.pro_work_client_link_json(i.owner_id,i.work_id);
 if not found or coalesce(w.cancelled,false) or linked is not null or not coalesce(public.pro_appointment_enabled(i.owner_id),false) then return jsonb_build_object('state','unavailable');end if;
 select * into prof from public.professionals where profile_id=i.owner_id and not coalesce(is_banned,false) order by id limit 1;
 return jsonb_build_object('state','valid','professionalName',left(coalesce(nullif(btrim(prof.business_name),''),'Profesional'),160),
  'service',coalesce(nullif(left(btrim(w.service),160),''),'Proyecto'),'expiresAt',i.expires_at);
end $$;

create or replace function public.pro_work_client_invitation_accept(p_actor uuid,p_input jsonb) returns jsonb
language plpgsql security invoker set search_path=public,pg_temp as $$
declare aid uuid;h text;i public.pro_work_client_invitations;prior public.pro_work_client_invitation_actions;rid uuid;st text;result jsonb;r public.pro_appointment_requests;
begin
 if not exists(select 1 from public.profiles where id=p_actor and not coalesce(is_disabled,false)) then raise exception 'Forbidden' using errcode='42501';end if;
 if jsonb_typeof(p_input) is distinct from 'object' or (select array_agg(key order by key) from jsonb_object_keys(p_input) key) is distinct from array['action','actionId','tokenHash']
  or p_input->>'action' is distinct from 'accept' or not coalesce(p_input->>'tokenHash'~'^[a-f0-9]{64}$',false) then raise exception 'Invalid acceptance' using errcode='22023';end if;
 aid:=(p_input->>'actionId')::uuid;h:=p_input->>'tokenHash';
 select * into i from public.pro_work_client_invitations where token_hash=h;
 if not found then raise exception 'Code unavailable' using errcode='P0002',hint='pro_invite_unknown';end if;
 -- Lock order: owner mutex -> invitation -> request (same as the owner mutations).
 perform pg_advisory_xact_lock(hashtextextended(i.owner_id::text,0));
 select * into prior from public.pro_work_client_invitation_actions where actor_id=p_actor and action_id=aid;
 if found then if prior.input is distinct from p_input then raise exception 'Action identity reused' using errcode='22023';end if;return prior.result||jsonb_build_object('replayed',true);end if;
 select * into i from public.pro_work_client_invitations where id=i.id for update;
 if i.accepted_by=p_actor then
  result:=jsonb_build_object('action','accept','requestId',i.request_id,'alreadyLinked',true);
 else
  st:=public.pro_work_client_invitation_state(i);
  if st='accepted' then raise exception 'Code used' using errcode='P0002',hint='pro_invite_used';end if;
  if st='revoked' then raise exception 'Code revoked' using errcode='P0002',hint='pro_invite_revoked';end if;
  if st='expired' then raise exception 'Code expired' using errcode='P0002',hint='pro_invite_expired';end if;
  if i.owner_id=p_actor then raise exception 'Own job' using errcode='42501',hint='pro_invite_own';end if;
  if not coalesce(public.pro_appointment_enabled(i.owner_id),false) then raise exception 'Professional unavailable' using errcode='40001',hint='pro_invite_work';end if;
  rid:=public.pro_work_client_link_apply(i.owner_id,i.work_id,p_actor);
  update public.pro_work_client_invitations set accepted_by=p_actor,accepted_at=clock_timestamp(),request_id=rid where id=i.id;
  select * into r from public.pro_appointment_requests where id=rid;
  result:=jsonb_build_object('action','accept','requestId',rid,'professionalName',r.professional_name,'service',r.service,'alreadyLinked',false);
 end if;
 insert into public.pro_work_client_invitation_actions(actor_id,action_id,input,result) values(p_actor,aid,p_input,result);
 return result;
end $$;

-- Estimate shared by code: consent of the verified recipient of an ACCEPTED version.
create or replace function public.pro_work_client_link_consent_read(p_actor uuid,p_publication uuid) returns jsonb
language plpgsql stable security invoker set search_path=public,pg_temp as $$
declare v public.pro_private_estimate_publications;s public.pro_private_estimate_publication_states;c public.pro_work_client_link_consents;a public.pro_private_estimate_work_agreements;r public.pro_appointment_requests;prof text;
begin
 if not exists(select 1 from public.profiles where id=p_actor and not coalesce(is_disabled,false)) then raise exception 'Forbidden' using errcode='42501';end if;
 select * into v from public.pro_private_estimate_publications where id=p_publication;
 select * into s from public.pro_private_estimate_publication_states where publication_id=p_publication;
 if v.id is null or s.recipient_id is distinct from p_actor then return null;end if;
 select left(coalesce(nullif(btrim(p.business_name),''),'Profesional'),160) into prof from public.professionals p where p.profile_id=v.owner_id order by p.id limit 1;
 select * into c from public.pro_work_client_link_consents where publication_id=p_publication and client_user_id=p_actor;
 select * into a from public.pro_private_estimate_work_agreements where publication_id=p_publication;
 if a.work_id is not null then select * into r from public.pro_appointment_requests where owner_id=v.owner_id and work_id=a.work_id and client_user_id=p_actor and status in('confirmed','completed');end if;
 -- Round 7A: a customer already linked to the job of this quote (its source job, or the job it was
 -- shared to as «linked customer») is not asked to join again.
 if r.id is null then
  select ar.* into r from public.pro_appointment_requests ar join public.pro_private_estimates d on d.owner_id=v.owner_id and d.id=v.estimate_id
   left join public.pro_private_estimate_publication_recipients b on b.owner_id=v.owner_id and b.estimate_id=v.estimate_id
   where ar.owner_id=v.owner_id and ar.client_user_id=p_actor and ar.status in('confirmed','completed') and ar.work_id is not null
    and(d.source->>'kind'='work' and ar.work_id=d.source->>'id' or b.proof->>'kind'='linked' and ar.id::text=b.proof->>'requestId')
   order by ar.updated_at desc,ar.id desc limit 1;
 end if;
 return jsonb_build_object('publicationId',p_publication,'eligible',s.status='accepted','consented',c.publication_id is not null,'consentedAt',c.at,
  'jobReady',a.work_id is not null or r.id is not null,'requestId',r.id,'professionalName',coalesce(prof,'Profesional'));
end $$;
create or replace function public.pro_work_client_link_consent(p_actor uuid,p_input jsonb) returns jsonb
language plpgsql security invoker set search_path=public,pg_temp as $$
declare aid uuid;pid uuid;v public.pro_private_estimate_publications;s public.pro_private_estimate_publication_states;a public.pro_private_estimate_work_agreements;prior public.pro_work_client_invitation_actions;rid uuid;status text;result jsonb;
begin
 if not exists(select 1 from public.profiles where id=p_actor and not coalesce(is_disabled,false)) then raise exception 'Forbidden' using errcode='42501';end if;
 if jsonb_typeof(p_input) is distinct from 'object' or (select array_agg(key order by key) from jsonb_object_keys(p_input) key) is distinct from array['action','actionId','publicationId']
  or p_input->>'action' is distinct from 'consent' then raise exception 'Invalid consent' using errcode='22023';end if;
 aid:=(p_input->>'actionId')::uuid;pid:=(p_input->>'publicationId')::uuid;
 select * into v from public.pro_private_estimate_publications where id=pid;if not found then raise exception 'Publication unavailable' using errcode='42501';end if;
 perform pg_advisory_xact_lock(hashtextextended(v.owner_id::text,0));
 select * into prior from public.pro_work_client_invitation_actions where actor_id=p_actor and action_id=aid;
 if found then if prior.input is distinct from p_input then raise exception 'Action identity reused' using errcode='22023';end if;return prior.result||jsonb_build_object('replayed',true);end if;
 select * into s from public.pro_private_estimate_publication_states where publication_id=pid for share;
 -- Only the verified recipient, and only once that version was accepted.
 if s.recipient_id is distinct from p_actor then raise exception 'Forbidden' using errcode='42501';end if;
 if s.status<>'accepted' then raise exception 'Accept the estimate first' using errcode='40001',hint='pro_consent_not_accepted';end if;
 insert into public.pro_work_client_link_consents(publication_id,owner_id,client_user_id) values(pid,v.owner_id,p_actor) on conflict(publication_id) do nothing;
 select * into a from public.pro_private_estimate_work_agreements where publication_id=pid;
 status:='pending';
 if found then
  begin rid:=public.pro_work_client_link_apply(v.owner_id,a.work_id,p_actor);status:='linked';
  exception when others then status:='unavailable';end;
  if rid is not null then update public.pro_work_client_link_consents set request_id=rid where publication_id=pid;end if;
 end if;
 result:=jsonb_build_object('action','consent','status',status,'requestId',rid);
 insert into public.pro_work_client_invitation_actions(actor_id,action_id,input,result) values(p_actor,aid,p_input,result);
 return result;
end $$;
-- When the owner continues an accepted estimate into a job, a recorded consent links the account.
-- A failure (e.g. another account already linked) never blocks the owner's continuation.
create or replace function public.pro_work_client_link_on_agreement() returns trigger
language plpgsql security invoker set search_path=public,pg_temp as $$
declare c public.pro_work_client_link_consents;rid uuid;
begin
 select * into c from public.pro_work_client_link_consents where publication_id=new.publication_id and client_user_id=new.accepted_actor_id;
 if found then
  begin perform pg_advisory_xact_lock(hashtextextended(new.owner_id::text,0));rid:=public.pro_work_client_link_apply(new.owner_id,new.work_id,c.client_user_id);
  exception when others then rid:=null;end;
  if rid is not null then update public.pro_work_client_link_consents set request_id=rid where publication_id=new.publication_id;end if;
 end if;
 return new;
end $$;
drop trigger if exists pro_work_client_link_on_agreement on public.pro_private_estimate_work_agreements;
create trigger pro_work_client_link_on_agreement after insert on public.pro_private_estimate_work_agreements for each row execute function public.pro_work_client_link_on_agreement();

-- Customer panel: jobs the account is linked to (any origin), newest first.
create or replace function public.pro_work_client_links_client(p_actor uuid) returns jsonb
language plpgsql stable security invoker set search_path=public,pg_temp as $$
declare items jsonb;
begin
 if not exists(select 1 from public.profiles where id=p_actor and not coalesce(is_disabled,false)) then raise exception 'Forbidden' using errcode='42501';end if;
 select coalesce(jsonb_agg(x.content order by x.at desc,x.id),'[]'::jsonb) into items from(
  select r.updated_at at,r.id,jsonb_build_object('requestId',r.id,'service',r.service,'professionalName',r.professional_name,'origin',r.origin,'linkedAt',r.updated_at,
   'stage',w.stage,'cancelled',coalesce(w.cancelled,false)) content
  from public.pro_appointment_requests r join public.pro_work w on w.user_id=r.owner_id and w.id=r.work_id
  where r.client_user_id=p_actor and r.status in('confirmed','completed') order by r.updated_at desc limit 50) x;
 return jsonb_build_object('items',items);
end $$;

