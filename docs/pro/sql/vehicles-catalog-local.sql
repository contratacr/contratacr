create table if not exists public.ref_vehicle_makes (
  id bigint generated always as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(btrim(name)) between 1 and 80),
  country_origin text check (country_origin is null or country_origin ~ '^[A-Z]{2}$'),
  vehicle_kinds text[] not null default '{}',
  active boolean not null default true,
  seed_status text not null default 'curated_seed_review' check (seed_status in ('curated_seed_review','reviewed')),
  created_at timestamptz not null default now()
);

create table if not exists public.ref_vehicle_models (
  id bigint generated always as identity primary key,
  make_id bigint not null references public.ref_vehicle_makes(id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(btrim(name)) between 1 and 80),
  vehicle_type text not null check (vehicle_type in ('car','suv','pickup','van','truck','motorcycle','atv')),
  active boolean not null default true,
  seed_status text not null default 'curated_seed_review' check (seed_status in ('curated_seed_review','reviewed')),
  created_at timestamptz not null default now(),
  unique (make_id, slug)
);
create index if not exists ref_vehicle_models_type_idx on public.ref_vehicle_models (vehicle_type, make_id);

