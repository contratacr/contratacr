/**
 * Builds the numbered Supabase migrations of ContrataCR Pro from the ordered local SQL manifest.
 *   node scripts/pro/build-pro-migrations.mjs          -> writes supabase/migrations/292+ (only if absent)
 *   node scripts/pro/build-pro-migrations.mjs --check  -> fails if the committed files differ from a fresh build
 * Never rewrites an applied migration: a file that exists is only compared. Pure file work, no DB.
 */
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {localSqlManifest} from './local-sql-manifest.mjs';

const root=new URL('../../',import.meta.url);
export const FIRST_NUMBER=292;
export const MAX_BYTES=200_000;
/** Local files already shipped as numbered migrations (byte-equivalent to their migration, verified by build --check). */
export const ALREADY_MIGRATED={
 'directory-core-local.sql':'270_dir_core.sql','directory-import-local.sql':'271_dir_import.sql','directory-claims-local.sql':'272_dir_claims.sql',
 'dir-business-roles-local.sql':'273_dir_business_roles.sql','directory-reviews-local.sql':'274_dir_reviews.sql','directory-search-local.sql':'275_dir_search.sql',
 'price-observations-local.sql':'276_price_observations.sql','directory-moderation-local.sql':'277_dir_moderation.sql','directory-import-extras-local.sql':'278_dir_import_extras.sql',
 'price-compare-local.sql':'279_price_compare.sql','pro-menu-local.sql':'280_dir_menus.sql','directory-price-search-local.sql':'281_dir_price_search.sql',
 'directory-place-tools-local.sql':'282_dir_place_tools.sql','directory-owner-profile-local.sql':'283_dir_owner_profile.sql','directory-reservations-local.sql':'284_dir_reservations.sql',
 'directory-questions-local.sql':'285_dir_questions.sql','directory-saved-lists-local.sql':'286_dir_saved_lists.sql','directory-events-local.sql':'287_dir_events.sql',
 'directory-brands-local.sql':'288_dir_brands.sql','directory-place-photos-local.sql':'289_dir_place_photos.sql','price-overview-local.sql':'290_price_overview.sql',
 'rate-limit-buckets-local.sql':'269_rate_limit_buckets.sql',
};
const norm=s=>s.replace(/--[^\n]*/g,'').replace(/\s+/g,' ').trim();
const read=async p=>readFile(new URL(p,root),'utf8');

/** One guarded install: skips the whole module when its anchor table already exists (the local installer's ifMissing). */
function guarded(text,anchor){
 const body=text.replace(/^\s*begin;\s*$/gim,'').replace(/^\s*commit;\s*$/gim,'');
 if(body.includes('$pro_install$'))throw Error('dollar-quote tag clash');
 return `do $pro_guard$ begin if to_regclass('${anchor}') is null then execute $pro_install$\n${body}\n$pro_install$; end if; end $pro_guard$;\n`;
}

export async function buildSteps(){
 const steps=[];
 for(const step of localSqlManifest){
  if(ALREADY_MIGRATED[step.file])continue;
  let text=await read('docs/pro/sql/'+step.file);
  if(step.ifMissing)text=guarded(text,step.ifMissing);
  steps.push({file:step.file,text:text.endsWith('\n')?text:text+'\n'});
 }
 return steps;
}

function slug(file){return file.replace(/-(local|draft)\.sql$/,'').replace(/\.sql$/,'').replace(/[^a-z0-9]+/g,'_');}

export async function buildMigrations(){
 const steps=await buildSteps(),groups=[];let cur=null;
 for(const s of steps){
  if(!cur||cur.bytes+s.text.length>MAX_BYTES){cur={steps:[],bytes:0};groups.push(cur);}
  cur.steps.push(s);cur.bytes+=s.text.length;
 }
 return groups.map((g,i)=>{
  const number=FIRST_NUMBER+i,name=`${number}_pro_${String(i+1).padStart(2,'0')}_${slug(g.steps[0].file)}.sql`;
  const header=[
   `-- ContrataCR Pro, database part ${i+1} of ${groups.length} (PRO_ENABLED stays false: nothing here turns Pro on).`,
   `-- Generated by scripts/pro/build-pro-migrations.mjs from the ordered local SQL manifest (scripts/pro/local-sql-manifest.mjs);`,
   `-- do not edit by hand: change docs/pro/sql and regenerate. Every module is idempotent (create if not exists / or replace /`,
   `-- guarded blocks) and keeps its own RLS, grants (service_role only unless stated) and pinned search_path.`,
   `-- Modules, in order:`,
   ...g.steps.map(s=>`--   ${s.file} sha256:${createHash('sha256').update(s.text).digest('hex').slice(0,12)}`),
   '',
  ].join('\n');
  const body=g.steps.map(s=>`-- ===== ${s.file} =====\n${s.text}`).join('\n');
  return {name,content:header+body};
 });
}

if(import.meta.url===new URL(process.argv[1],'file:').href||process.argv[1]?.endsWith('build-pro-migrations.mjs')){
 const check=process.argv.includes('--check'),out=await buildMigrations(),existing=new Set(await readdir(new URL('supabase/migrations/',root)));
 // Already-migrated local files must stay equivalent to their migration (otherwise a delta migration is needed).
 for(const[local,mig]of Object.entries(ALREADY_MIGRATED)){
  const a=norm(await read('docs/pro/sql/'+local)),b=norm(await read('supabase/migrations/'+mig));
  if(!b.includes(a))throw Error(`${local} drifted from ${mig}: write a delta migration`);
 }
 let bad=0;
 for(const m of out){
  const path='supabase/migrations/'+m.name;
  if(existing.has(m.name)){const cur=await read(path);if(cur!==m.content){console.error('DIFFERS: '+m.name);bad++;}}
  else if(check){console.error('MISSING: '+m.name);bad++;}
  else await writeFile(new URL(path,root),m.content);
 }
 const mine=[...existing].filter(n=>/^\d+_pro_\d\d_/.test(n)&&Number(n.split('_')[0])>=FIRST_NUMBER);
 for(const n of mine)if(!out.some(m=>m.name===n)){console.error('EXTRA: '+n);bad++;}
 if(bad)process.exit(1);
 console.log(`${out.length} Pro migrations ${check?'verified':'ready'}: ${out.map(m=>m.name.split('_')[0]).join(', ')}`);
}
