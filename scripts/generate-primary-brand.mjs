import fs from 'node:fs/promises';
import sharp from 'sharp';
// Same artwork, geometry and gap as ContrataCRLogo; raster exports never typeset the brand.
const mark = await sharp('public/logo-mark-transparent.png').resize(128,128).png().toBuffer();
const word = await sharp('public/brand/wordmark-light.svg',{density:288}).resize(420,96).png().toBuffer();
const logo = await sharp({create:{width:548,height:128,channels:4,background:'#00000000'}}).composite([{input:mark,left:0,top:0},{input:word,left:128,top:16}]).png().toBuffer();
await fs.writeFile('public/brand/logo-primary.png',logo);
await fs.writeFile('public/logo-wordmark-transparent.png',logo);
const email = await sharp(logo).flatten({background:'#ffffff'}).png().toBuffer();
for(const name of ['email-logo-primary','email-logo-light','email-logo-dark']) await fs.writeFile(`public/brand/${name}.png`,email);
const symbol=await fs.readFile('public/logo-mark-transparent.png');
await fs.writeFile('src/lib/og-logos.ts',`// Generated by scripts/generate-primary-brand.mjs from the official navbar artwork.\nexport const LOGO_PALABRA = "data:image/png;base64,${logo.toString('base64')}";\nexport const LOGO_SIMBOLO = "data:image/png;base64,${symbol.toString('base64')}";\n`);
