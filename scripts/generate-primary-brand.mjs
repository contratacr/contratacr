import fs from 'node:fs/promises';
import sharp from 'sharp';
// Same artwork, geometry and gap as ContrataCRLogo; raster exports never typeset the brand.
const mark = await sharp('public/logo-mark-transparent.png').resize(128,128).png().toBuffer();
const word = await sharp('public/brand/wordmark-light.svg',{density:288}).resize(420,96).png().toBuffer();
const logo = await sharp({create:{width:548,height:128,channels:4,background:'#00000000'}}).composite([{input:mark,left:0,top:0},{input:word,left:128,top:16}]).png().toBuffer();
await fs.writeFile('public/brand/logo-primary.png',logo);
await fs.writeFile('public/logo-wordmark-transparent.png',logo);
// Email variants stay transparent; the client selects one for its color scheme.
// Keep the old URL readable in emails already sent with a single logo.
await fs.writeFile('public/brand/email-logo-primary.png', await sharp(logo).flatten({background:'#ffffff'}).png().toBuffer());
await fs.writeFile('public/brand/email-logo-light.png', logo);
const darkMark = await sharp('public/logo-mark-dark.png').resize(128,128).png().toBuffer();
const darkWord = await sharp('public/brand/wordmark-dark.svg',{density:288}).resize(420,96).png().toBuffer();
const darkEmail = await sharp({create:{width:548,height:128,channels:4,background:'#00000000'}}).composite([{input:darkMark,left:0,top:0},{input:darkWord,left:128,top:16}]).png().toBuffer();
await fs.writeFile('public/brand/email-logo-dark.png', darkEmail);
// Sharing cards draw the symbol at 480px. Rasterize the original paths
// at twice that resolution instead of enlarging the 256px navbar bitmap.
const symbol=await sharp('public/logo.svg', {density:192}).resize(960,960,{fit:'contain',background:'#00000000'}).png().toBuffer();
await fs.writeFile('src/lib/og-logos.ts',`// Generated by scripts/generate-primary-brand.mjs from the official navbar artwork.\nexport const LOGO_PALABRA = "data:image/png;base64,${logo.toString('base64')}";\nexport const LOGO_SIMBOLO = "data:image/png;base64,${symbol.toString('base64')}";\n`);
