#!/usr/bin/env node
// LOCAL PRO ONLY (salud cleanup, owner request 2026-11-17). Offline: reads LOCAL Overpass/GeoJSON dumps and prints ONE SQL
// file that applies the health exclusion/reclass list of stage-import.mjs to places already imported, through the normal
// staff path with history:
//   * excluded (isExcludedHealth: healthcare=alternative, retreat/ceremony names; HEALTH_EXCLUDED_REFS) → dir_place_mutate
//     action 'status' → 'hidden' (unpublished, reversible, before/after in dir_place_history);
//   * reclassified (HEALTH_RECLASS, e.g. Banco Nacional de Sangre → kind blood_bank, publicService) → dir_place_mutate
//     action 'update' with the merged attributes (history + provenance from source osm).
// Only places still in section 'health', published and UNCLAIMED are touched (claimed ones are reported, never changed).
// Action ids are derived from the actor + reference (dir_derived_uuid), so re-running is idempotent. Every row writes a
// line to a result table printed at the end (ref, name, decision, outcome).
// Usage: node scripts/directory/health-cleanup.mjs --actor <staff-uuid> --out <file.sql> <dump.json> [...]
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {HEALTH_EXCLUDED_REFS,HEALTH_RECLASS,classifyTags,isExcludedHealth} from './stage-import.mjs';

const HEALTH_AMENITY=new Set(['clinic','doctors','dentist','hospital']);
const wasHealth=t=>HEALTH_AMENITY.has(t.amenity)||(typeof t.healthcare==='string'&&!['pharmacy','blood_donation'].includes(t.healthcare))||t.shop==='optician';
const refOf=e=>e.type&&e.id!=null?`${e.type}/${e.id}`:typeof e.id==='string'&&/^(node|way|relation)\/\d+$/.test(e.id)?e.id:e.properties?.['@id']??null;
/** Pure plan from OSM elements: [{ref, name, decision:'hide'|'reclass', reason, attributes?}], sorted by ref. */
export function healthCleanupPlan(elements){
 const plan=new Map();
 for(const e of elements){
  const tags=e.tags??e.properties??{},ref=refOf(e);if(!ref||plan.has(ref))continue;
  if(HEALTH_EXCLUDED_REFS[ref])plan.set(ref,{ref,name:tags.name??null,decision:'hide',reason:HEALTH_EXCLUDED_REFS[ref]});
  else if(wasHealth(tags)&&isExcludedHealth(tags)&&classifyTags(tags)?.vertical!=='health')plan.set(ref,{ref,name:tags.name??null,decision:'hide',reason:tags.healthcare==='alternative'?'alternative_therapy':'retreat_or_ceremony'});
  else if(HEALTH_RECLASS[ref])plan.set(ref,{ref,name:tags.name??null,decision:'reclass',reason:'subtype',attributes:{...HEALTH_RECLASS[ref]}});
 }
 return [...plan.values()].sort((a,b)=>a.ref.localeCompare(b.ref));
}
const lit=v=>"'"+String(v).replace(/'/g,"''")+"'";
export function healthCleanupSql(plan,actor){
 if(!/^[0-9a-f-]{36}$/i.test(actor))throw new Error('--actor must be a uuid');
 const rows=plan.map(p=>`(${lit(p.ref)},${lit(p.decision)},${lit(p.reason)},${p.attributes?lit(JSON.stringify(p.attributes))+'::jsonb':'null'})`).join(',\n ');
 return `-- Generated by scripts/directory/health-cleanup.mjs (salud cleanup 2026-11-17). Staff path with history; idempotent.
begin;
create temp table health_cleanup_result(ref text,name text,decision text,reason text,outcome text) on commit preserve rows;
do $$declare r record;p public.dir_places;act uuid:=${lit(actor)}::uuid;res jsonb;
begin
 for r in select * from (values
 ${rows}
 ) v(ref,decision,reason,attrs) loop
  p:=public.dir_import_ref_place('osm',r.ref);
  if p.id is null then insert into health_cleanup_result values(r.ref,null,r.decision,r.reason,'not_imported');continue;end if;
  if p.vertical_id<>'health' then insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'other_section:'||p.vertical_id);continue;end if;
  if p.claim_status<>'unclaimed' then insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'claimed_kept');continue;end if;
  if r.decision='hide' then
   if p.status<>'published' then insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'already_'||p.status);continue;end if;
   res:=public.dir_place_mutate(act,jsonb_build_object('action','status','actionId',public.dir_derived_uuid(act,'health-cleanup:hide:'||r.ref),'placeId',p.id,'revision',p.revision,'status','hidden'));
   insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'hidden');
  else
   if p.attributes@>r.attrs then insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'already_reclassified');continue;end if;
   res:=public.dir_place_mutate(act,jsonb_build_object('action','update','actionId',public.dir_derived_uuid(act,'health-cleanup:reclass:'||r.ref),'placeId',p.id,'revision',p.revision,
    'place',jsonb_build_object('attributes',p.attributes||r.attrs),'source',jsonb_build_object('id','contratacr')));
   insert into health_cleanup_result values(r.ref,p.name,r.decision,r.reason,'reclassified:'||(p.attributes||r.attrs)::text);
  end if;
 end loop;
end $$;
select ref,name,decision,reason,outcome from health_cleanup_result order by decision,name;
commit;
`;
}
async function main(argv){
 const args=[...argv],files=[];let actor=null,out=null;
 while(args.length){const a=args.shift();if(a==='--actor')actor=args.shift();else if(a==='--out')out=args.shift();else files.push(a);}
 if(!actor||!out||!files.length){console.error('Usage: health-cleanup.mjs --actor <uuid> --out <file.sql> <dump.json>...');process.exit(2);}
 const elements=[];for(const f of files){const d=JSON.parse(await readFile(f,'utf8'));elements.push(...(d.elements??d.features??[]));}
 const plan=healthCleanupPlan(elements);
 await writeFile(out,healthCleanupSql(plan,actor));
 console.log(JSON.stringify({files:files.length,elements:elements.length,plan},null,1));
}
if(import.meta.url===pathToFileURL(process.argv[1]??'').href)await main(process.argv.slice(2));
